// La llave con que se firma la app que se entrega. Vive fuera del repositorio
// (por defecto, ~/Android/claves/keystore.properties; o donde diga
// DANPLAY_KEYSTORE): un telefono solo acepta una actualizacion firmada con la
// misma llave que la que tiene instalada. Sin ella, el APK sale sin firmar.
val keystoreProperties = Properties().apply {
    val path = System.getenv("DANPLAY_KEYSTORE")
        ?: (System.getProperty("user.home") + "/Android/claves/keystore.properties")
    val propFile = file(path)
    if (propFile.exists()) {
        propFile.inputStream().use { load(it) }
    }
}

